import { chromium } from "playwright-core";
import { openApp } from "./target.mjs";
const browser = await chromium.launch({ channel: "chrome", headless: true });
const page = await (await browser.newContext({ viewport: { width: 1540, height: 920 } })).newPage();
await openApp(page); await page.waitForSelector(".node");
const z0 = await page.textContent("#zoomLabel");
await page.click("#zoomIn"); await page.click("#zoomIn");
const z1 = await page.textContent("#zoomLabel");
await page.click("#zoomFit"); const z2 = await page.textContent("#zoomLabel");
const stage = await page.locator("#stage").boundingBox();
const outside = await page.$$eval("#nodes .node", (nodes, st) => nodes.filter((n) => {
  const b = n.getBoundingClientRect();
  return b.left < st.x - 1 || b.top < st.y - 1 || b.right > st.x + st.width + 1 || b.bottom > st.y + st.height + 1;
}).length, stage);
const percent = (label) => Number.parseInt(label, 10);
const r = { before: z0, afterZoomIn2x: z1, afterFitBtn: z2, nodesOutsideAfterFit: outside };
const fail = (msg) => { if (!r.FAILED) r.FAILED = msg; };
if (!(percent(z1) > percent(z0))) fail(`zoom + deveria aumentar o zoom: ${z0} → ${z1}`);
if (outside > 0) fail(`enquadrar deveria mostrar todos os cards: ${outside} fora da área`);
console.log(r);
await browser.close();
